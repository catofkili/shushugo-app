import assert from 'node:assert/strict';
import { observeFirst,inPool } from './gates.mjs';
import { selectDue } from './simulator.mjs';
import { configurations } from './r2-grid.mjs';

const word={card:{lapses:8},recentFirst:[]};
const answer=g=>observeFirst(word,word.card.lapses,g);
assert(inPool(word,'F1'));
answer(4);observeFirst(word,8);observeFirst(word,8);
assert(inPool(word,'F1'),'Same-day successes cannot release');
answer(3);assert(!inPool(word,'F1'));
answer(1);assert(!inPool(word,'F1'),'One later lapse cannot reenter');
answer(2);answer(4);assert(!inPool(word,'F1'));
answer(1);assert(inPool(word,'F1'),'Two later forgotten first answers must reenter');
answer(4);answer(4);assert(!inPool(word,'F1'));
assert(inPool(word,'L8/10'),'Legacy threshold is never forgiven');
assert(!inPool(word,'L0'));assert(!inPool(word,'F3'));
const fresh={card:{lapses:7},recentFirst:[]};
for(const g of [1,1,1,1,1])observeFirst(fresh,7,g);
assert(inPool(fresh,'F2'),'F2 is independent of lifetime lapses');
for(const g of [2,3,3,3,3,3])observeFirst(fresh,7,g);
assert(!inPool(fresh,'F2'),'Old failures leave the rolling window');
assert.equal(fresh.recentFirst.length,10);
const normal=[{card:{lapses:0}},{card:{lapses:7}}],hard=[{card:{lapses:8}},{card:{lapses:20}}];
const take=(a,n)=>a.slice(0,n),c={gate:'F3',selection:'random',intake:10};
assert.deepEqual(selectDue([...hard,...normal],c,1,take),normal.slice(0,1));
assert.deepEqual(selectDue([...hard,...normal],c,3,take),[...normal,hard[0]]);
assert.deepEqual(selectDue([...hard,...normal],c,4,take),[...normal,...hard]);
assert.deepEqual(selectDue(hard,{gate:'L8/10',intake:1},3,take),hard.slice(0,1));
assert.equal(configurations().length,48);
console.log('ROUND 2 RULE CHECKS OK: forgiveness, reentry, rolling history, gate intake, priority, grid');
