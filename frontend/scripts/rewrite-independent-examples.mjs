const clean = (value) => String(value ?? "")
  .replace(/<[^>]+>/gu, "")
  .replace(/\s+/gu, " ")
  .trim();

const meaningLabel = (meaning, fallback) => {
  const value = clean(meaning)
    .replace(/[⓪①②③④⑤⑥⑦⑧⑨]/gu, "")
    .replace(/^（[^）]*）/u, "")
    .replace(/^\([^)]*\)/u, "")
    .split(/[；;，,、]/u)[0]
    .replace(/[.…~〜]+/gu, "")
    .trim();
  return value || fallback;
};

const normalizeTerm = (kanji, kana) => {
  const raw = clean(kanji);
  const withoutReading = raw.replace(/\[[^\]]*\]/gu, "").trim();
  const looksLikeJapanese = /^[ぁ-んァ-ヶ一-龯々ー・]+$/u.test(withoutReading);
  if (!looksLikeJapanese || /〜|~|[A-Za-z；;]/u.test(raw)) {
    return clean(kana).replace(/^[〜~]/u, "") || withoutReading || clean(kana);
  }
  return withoutReading || clean(kana);
};

