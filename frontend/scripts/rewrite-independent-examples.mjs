const verbTypeFor = (verbType, term, kana) => {
  if (verbType === "suru" || term.endsWith("する") || kana.endsWith("する")) return "suru";
  if (verbType === "kuru" || term === "来る") return "kuru";
  if (verbType === "iku" || term === "行く") return "iku";
  if (godanRuExceptions.has(term)) return "godan";
  if (godanRuEndings.some((ending) => term.endsWith(ending))) return "godan";
  if (verbType === "ichidan") return "ichidan";
  if (verbType === "godan") return "godan";
  return null;
};

const masuForm = (term, kana, verbType) => {
  const type = verbTypeFor(verbType, term, kana);
  if (!type) return null;
  if (type === "suru") return term.endsWith("する") ? `${term.slice(0, -2)}します` : `${term}します`;
  if (type === "kuru") return "来ます";
  if (type === "iku") return "行きます";
  if (type === "ichidan") return term.endsWith("る") ? `${term.slice(0, -1)}ます` : null;
  const endings = new Map([["う", "います"], ["く", "きます"], ["ぐ", "ぎます"], ["す", "します"], ["つ", "ちます"], ["ぬ", "にます"], ["ぶ", "びます"], ["む", "みます"], ["る", "ります"]]);
  const ending = kana.slice(-1);
  const replacement = endings.get(ending);
  return replacement ? `${term.slice(0, -1)}${replacement}` : null;
};

const dictionaryForm = (term, kana, verbType) => {
  const type = verbTypeFor(verbType, term, kana);
  if (type === "suru" && !term.endsWith("する")) return `${term}する`;
  return term;
};

