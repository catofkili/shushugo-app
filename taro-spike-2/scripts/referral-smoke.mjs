// 读 dist 构建产物，只挂在 build:weapp 末尾；别放回 npm test（CI 和 ci-local 不构建 Taro，dist 不存在）。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { ROUTE_TABLE } = require('../src/platform/route-table.cjs');
const invite = ROUTE_TABLE.find((route) => route.page === 'invite');
assert.equal(invite?.subpackage, 'study');
assert.equal(invite?.tab, false);
const app = JSON.parse(fs.readFileSync(path.join(root, 'dist/app.json'), 'utf8'));
assert(app.subPackages.find((pack) => pack.root === 'study').pages.includes('invite/index'));
const read = (file) => fs.readFileSync(path.join(root, 'dist', file), 'utf8');
const page = read('study/invite/index.js');
assert(!/柚子|奖励|套装|翻倍/.test(page), 'Invite page must not include incentive copy');
assert(page.includes('/study/invite/index?ref='), 'Share must prefill this subpackage page');
const home = read('lazy/tabs.js');
assert(!/柚子多得|套装/.test(home), 'Home referral entry must not include incentive copy');
const css = read('app.wxss');
assert(css.includes('.skin-theme-dusk'), 'Dusk must reach the native page theme');
assert(read('study/invite/index.wxss').includes('zoo-tm-invite-ticket'), 'Shared ticket CSS must reach invite page');
console.log('Referral subpackage, share path, incentive-free invitation/home and native dusk theme passed.');
